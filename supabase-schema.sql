create policy "Students can read own profile"
on public.students for select
to authenticated
using (id = auth.uid());

create policy "Students can read own universities"
on public.universities for select
to authenticated
using (student_id = auth.uid());

create policy "Students can update own universities"
on public.universities for update
to authenticated
using (student_id = auth.uid())
with check (student_id = auth.uid());

create policy "Students can read own university history"
on public.university_history for select
to authenticated
using (
  exists (
    select 1 from public.universities
    where universities.id = university_history.university_id
    and universities.student_id = auth.uid()
  )
);

