-- getConsultantUser(), which bypasses RLS. These policies are the second layer
-- — they make the tables safe even if reached directly through PostgREST with
-- an anon or authenticated key (anon has no applicable policy, so it fails
-- closed; a non-consultant authenticated user matches none either).
